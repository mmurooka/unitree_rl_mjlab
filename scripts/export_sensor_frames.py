#!/usr/bin/env python3
"""Export fixed G1 kinematics from MJCF for sim/real sensor consumers.

MuJoCo is needed only to regenerate this file, never to read simulation state.
All transforms below are model constants. Runtime consumers supply measured q.
"""
from pathlib import Path
import argparse
import hashlib

import mujoco
import numpy as np
import yaml

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_MODEL = ROOT / 'src/assets/robots/unitree_g1/xmls/scene_g1.xml'
DEFAULT_OUTPUT = ROOT / 'config/g1_sensor_frames.yaml'


def export(model_path: Path) -> dict:
    model = mujoco.MjModel.from_xml_path(str(model_path))
    root = model.body('pelvis').id
    torso = model.body('torso_link').id
    chain = []
    body = torso
    while body != root:
        if body == 0:
            raise ValueError('torso must descend from pelvis')
        chain.append(body)
        body = int(model.body_parentid[body])
    joints = []
    for body in reversed(chain):
        if model.body_jntnum[body] != 1:
            raise ValueError('expected one hinge per waist body')
        joint = int(model.body_jntadr[body])
        if model.jnt_type[joint] != mujoco.mjtJoint.mjJNT_HINGE:
            raise ValueError('expected waist hinge')
        actuator = np.flatnonzero(model.actuator_trnid[:, 0] == joint)
        if len(actuator) != 1:
            raise ValueError('expected one actuator per waist joint')
        joints.append(dict(
            name=mujoco.mj_id2name(model, mujoco.mjtObj.mjOBJ_JOINT, joint),
            sdk_index=int(actuator[0]),
            translation=model.body_pos[body].tolist(),
            quaternion_wxyz=model.body_quat[body].tolist(),
            axis=model.jnt_axis[joint].tolist(),
            pivot=model.jnt_pos[joint].tolist(),
        ))
    lidar = model.site('livox_frame').id
    camera = model.camera('camera_color_optical_frame').id
    camera_body = int(model.cam_bodyid[camera])
    if model.site_bodyid[lidar] != torso or model.body_parentid[camera_body] != torso:
        raise ValueError('sensors must attach to torso')
    if model.body_jntnum[camera_body]:
        raise ValueError('camera mount must be fixed')
    # MuJoCo cameras look along -Z with +Y up. ROS optical uses +Z, +Y down.
    from robot_frames import transform
    torso_camera = transform(model.body_pos[camera_body], model.body_quat[camera_body])
    torso_camera = torso_camera @ transform(model.cam_pos[camera], model.cam_quat[camera])
    torso_camera[:3, :3] = torso_camera[:3, :3] @ np.diag([1., -1., -1.])
    return dict(
        schema_version=1,
        source_model=str(model_path.relative_to(ROOT)),
        source_sha256=hashlib.sha256(model_path.read_bytes()).hexdigest(),
        root_frame='pelvis',
        horizontal_frame='root_yaw',
        # The simulator's G1 bridge uses actuator order == SDK motor order.
        waist=joints,
        torso_to_lidar=transform(model.site_pos[lidar], model.site_quat[lidar]).tolist(),
        torso_to_color_optical=torso_camera.tolist(),
    )


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--model', type=Path, default=DEFAULT_MODEL)
    parser.add_argument('--output', type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()
    args.output.write_text(
        '# Generated by scripts/export_sensor_frames.py; fixed model data only.\n'
        + yaml.safe_dump(export(args.model), sort_keys=False), encoding='utf-8')
